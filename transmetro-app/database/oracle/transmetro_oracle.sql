    ACCION VARCHAR2(100) NOT NULL,
    TABLA_AFECTADA VARCHAR2(100),
    ID_REGISTRO_AFECTADO NUMBER,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
