/* ============================================================
   SISTEMA DE GESTIÓN Y CONTROL DE TRANSMETRO
   BASE DE DATOS ORACLE
   ============================================================ */

/* ============================================================
   1. TABLAS DE SEGURIDAD Y USUARIOS
   ============================================================ */

CREATE TABLE ROLES (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200),
    CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ROL NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    USUARIO VARCHAR2(50) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT FK_USUARIOS_ROLES
        FOREIGN KEY (ID_ROL) REFERENCES ROLES(ID_ROL),
    CONSTRAINT UQ_USUARIOS_USUARIO UNIQUE (USUARIO),
    CONSTRAINT UQ_USUARIOS_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

/* ============================================================
   2. MUNICIPALIDADES
   ============================================================ */

CREATE TABLE MUNICIPALIDADES (
    ID_MUNICIPALIDAD NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DEPARTAMENTO VARCHAR2(100),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_MUNICIPALIDADES PRIMARY KEY (ID_MUNICIPALIDAD),

    CONSTRAINT UQ_MUNICIPALIDADES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_MUNICIPALIDADES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

/* ============================================================
   3. LINEAS
   ============================================================ */

CREATE TABLE LINEAS (
    ID_LINEA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_MUNICIPALIDAD NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(250),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT PK_LINEAS PRIMARY KEY (ID_LINEA),
    CONSTRAINT FK_LINEAS_MUNICIPALIDADES
        FOREIGN KEY (ID_MUNICIPALIDAD)
        REFERENCES MUNICIPALIDADES(ID_MUNICIPALIDAD),
    CONSTRAINT UQ_LINEAS_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_LINEAS_ESTADO
        CHECK (ESTADO IN ('ACTIVA', 'INACTIVA'))
);

/* ============================================================
   4. ESTACIONES
   ============================================================ */

CREATE TABLE ESTACIONES (
    ID_ESTACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_MUNICIPALIDAD NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(250),
    LATITUD NUMBER(10,7),
    LONGITUD NUMBER(10,7),
    TIENE_PARQUEO CHAR(1) DEFAULT 'N' NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT PK_ESTACIONES PRIMARY KEY (ID_ESTACION),
    CONSTRAINT FK_ESTACIONES_MUNICIPALIDADES
        FOREIGN KEY (ID_MUNICIPALIDAD)
        REFERENCES MUNICIPALIDADES(ID_MUNICIPALIDAD),
    CONSTRAINT UQ_ESTACIONES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_ESTACIONES_PARQUEO
        CHECK (TIENE_PARQUEO IN ('S', 'N')),
    CONSTRAINT CK_ESTACIONES_ESTADO
        CHECK (ESTADO IN ('ACTIVA', 'INACTIVA', 'MANTENIMIENTO'))
);

/* ============================================================
   5. RELACIÓN ENTRE LINEAS Y ESTACIONES
   ============================================================ */

CREATE TABLE LINEA_ESTACION (
    ID_LINEA NUMBER NOT NULL,
    ID_ESTACION NUMBER NOT NULL,
    ORDEN_ESTACION NUMBER NOT NULL,
    DISTANCIA_DESDE_ANTERIOR NUMBER(10,2),

    CONSTRAINT PK_LINEA_ESTACION
        PRIMARY KEY (ID_LINEA, ID_ESTACION),
    CONSTRAINT FK_LE_LINEAS
        FOREIGN KEY (ID_LINEA) REFERENCES LINEAS(ID_LINEA),
    CONSTRAINT FK_LE_ESTACIONES
        FOREIGN KEY (ID_ESTACION) REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT UQ_LE_ORDEN
        UNIQUE (ID_LINEA, ORDEN_ESTACION),
    CONSTRAINT CK_LE_ORDEN
        CHECK (ORDEN_ESTACION > 0),
    CONSTRAINT CK_LE_DISTANCIA
        CHECK (
            DISTANCIA_DESDE_ANTERIOR IS NULL
            OR DISTANCIA_DESDE_ANTERIOR >= 0
        )
);

/* ============================================================
   6. ACCESOS Y GUARDIAS DE SEGURIDAD
   ============================================================ */

CREATE TABLE ACCESOS (
    ID_ACCESO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACION NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    TIPO VARCHAR2(30),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_ACCESOS PRIMARY KEY (ID_ACCESO),
    CONSTRAINT FK_ACCESOS_ESTACIONES
        FOREIGN KEY (ID_ESTACION)
        REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT CK_ACCESOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'MANTENIMIENTO'))
);

CREATE TABLE GUARDIAS (
    ID_GUARDIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(30),
    CORREO VARCHAR2(150),

    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_GUARDIAS PRIMARY KEY (ID_GUARDIA),
    CONSTRAINT CK_GUARDIAS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE ACCESO_GUARDIA (
    ID_ACCESO NUMBER NOT NULL,
    ID_GUARDIA NUMBER NOT NULL,
    FECHA_INICIO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_FIN DATE,

    CONSTRAINT PK_ACCESO_GUARDIA
        PRIMARY KEY (ID_ACCESO, ID_GUARDIA, FECHA_INICIO),
    CONSTRAINT FK_AG_ACCESOS
        FOREIGN KEY (ID_ACCESO) REFERENCES ACCESOS(ID_ACCESO),
    CONSTRAINT FK_AG_GUARDIAS
        FOREIGN KEY (ID_GUARDIA) REFERENCES GUARDIAS(ID_GUARDIA),
    CONSTRAINT CK_AG_FECHAS
        CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

/* ============================================================
   7. PILOTOS Y OPERADORES
   ============================================================ */

CREATE TABLE PILOTOS (
    ID_PILOTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(30),
    CORREO VARCHAR2(150),
    DIRECCION VARCHAR2(250),
    FORMACION_ACADEMICA VARCHAR2(250),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_PILOTOS PRIMARY KEY (ID_PILOTO),
    CONSTRAINT CK_PILOTOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE OPERADORES_ESTACION (
    ID_OPERADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_ESTACION NUMBER NOT NULL,
    FECHA_ASIGNACION DATE DEFAULT SYSDATE NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_OPERADORES PRIMARY KEY (ID_OPERADOR),
    CONSTRAINT FK_OE_USUARIOS
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),

    CONSTRAINT FK_OE_ESTACIONES
        FOREIGN KEY (ID_ESTACION) REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT CK_OE_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

/* ============================================================
   8. PARQUEOS
   ============================================================ */

CREATE TABLE PARQUEOS (
    ID_PARQUEO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACION NUMBER NOT NULL,
    CODIGO VARCHAR2(50) NOT NULL,
    UBICACION VARCHAR2(250),
    ESTADO VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,

    CONSTRAINT PK_PARQUEOS PRIMARY KEY (ID_PARQUEO),
    CONSTRAINT FK_PARQUEOS_ESTACIONES
        FOREIGN KEY (ID_ESTACION)
        REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT UQ_PARQUEOS_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_PARQUEOS_ESTADO
        CHECK (ESTADO IN ('DISPONIBLE', 'OCUPADO', 'MANTENIMIENTO'))
);

/* ============================================================
   9. BUSES
   ============================================================ */

CREATE TABLE BUSES (
    ID_BUS NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PLACA VARCHAR2(20) NOT NULL,
    NUMERO_INTERNO VARCHAR2(30) NOT NULL,
    CAPACIDAD_MAXIMA NUMBER NOT NULL,
    ESTADO VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_BUSES PRIMARY KEY (ID_BUS),
    CONSTRAINT UQ_BUSES_PLACA UNIQUE (PLACA),
    CONSTRAINT UQ_BUSES_NUMERO UNIQUE (NUMERO_INTERNO),
    CONSTRAINT CK_BUSES_CAPACIDAD
        CHECK (CAPACIDAD_MAXIMA > 0),
    CONSTRAINT CK_BUSES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'MANTENIMIENTO'))
);

/* ============================================================
   10. ASIGNACIÓN DE BUSES A LINEAS
   ============================================================ */

CREATE TABLE BUS_LINEA (
    ID_BUS NUMBER NOT NULL,
    ID_LINEA NUMBER NOT NULL,
    FECHA_INICIO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_FIN DATE,

    CONSTRAINT PK_BUS_LINEA
        PRIMARY KEY (ID_BUS, FECHA_INICIO),
    CONSTRAINT FK_BL_BUSES
        FOREIGN KEY (ID_BUS) REFERENCES BUSES(ID_BUS),
    CONSTRAINT FK_BL_LINEAS
        FOREIGN KEY (ID_LINEA) REFERENCES LINEAS(ID_LINEA),
    CONSTRAINT CK_BL_FECHAS
        CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

/* ============================================================
   11. HISTORIAL DE PARQUEO DE BUSES
   ============================================================ */

CREATE TABLE BUS_PARQUEO (
    ID_BUS_PARQUEO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_BUS NUMBER NOT NULL,
    ID_PARQUEO NUMBER NOT NULL,
    FECHA_INICIO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_FIN DATE,

    CONSTRAINT PK_BUS_PARQUEO PRIMARY KEY (ID_BUS_PARQUEO),
    CONSTRAINT FK_BP_BUSES
        FOREIGN KEY (ID_BUS) REFERENCES BUSES(ID_BUS),
    CONSTRAINT FK_BP_PARQUEOS
        FOREIGN KEY (ID_PARQUEO) REFERENCES PARQUEOS(ID_PARQUEO),
    CONSTRAINT CK_BP_FECHAS
        CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

/* ============================================================
   12. TICKETS Y METODOS DE PAGO
   ============================================================ */

CREATE TABLE METODOS_PAGO (
    ID_METODO_PAGO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_METODOS_PAGO PRIMARY KEY (ID_METODO_PAGO),
    CONSTRAINT UQ_METODOS_PAGO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_MP_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE PASAJEROS (
    ID_PASAJERO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100),
    APELLIDO VARCHAR2(100),
    IDENTIFICADOR VARCHAR2(100),
    TIPO_PASAJERO VARCHAR2(30),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_PASAJEROS PRIMARY KEY (ID_PASAJERO),
    CONSTRAINT UQ_PASAJEROS_IDENTIFICADOR UNIQUE (IDENTIFICADOR),
    CONSTRAINT CK_PASAJEROS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE TICKETS (
    ID_TICKET NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PASAJERO NUMBER,
    ID_METODO_PAGO NUMBER NOT NULL,
    CODIGO_TICKET VARCHAR2(100) NOT NULL,
    FECHA_EMISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VALOR NUMBER(10,2) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'VALIDO' NOT NULL,

    CONSTRAINT PK_TICKETS PRIMARY KEY (ID_TICKET),
    CONSTRAINT FK_TICKETS_PASAJEROS
        FOREIGN KEY (ID_PASAJERO) REFERENCES PASAJEROS(ID_PASAJERO),
    CONSTRAINT FK_TICKETS_METODOS
        FOREIGN KEY (ID_METODO_PAGO)
        REFERENCES METODOS_PAGO(ID_METODO_PAGO),
    CONSTRAINT UQ_TICKETS_CODIGO UNIQUE (CODIGO_TICKET),
    CONSTRAINT CK_TICKETS_VALOR CHECK (VALOR >= 0),
    CONSTRAINT CK_TICKETS_ESTADO
        CHECK (ESTADO IN ('VALIDO', 'UTILIZADO', 'ANULADO', 'VENCIDO'))
);

/* ============================================================
   13. DISPOSITIVOS TECNOLOGICOS
   ============================================================ */

CREATE TABLE DISPOSITIVOS (
    ID_DISPOSITIVO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACION NUMBER,
    ID_BUS NUMBER,
    CODIGO_INVENTARIO VARCHAR2(100) NOT NULL,
    TIPO VARCHAR2(40) NOT NULL,
    ESTADO VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_INSTALACION DATE,

    CONSTRAINT PK_DISPOSITIVOS PRIMARY KEY (ID_DISPOSITIVO),
    CONSTRAINT FK_DISPOSITIVOS_ESTACIONES
        FOREIGN KEY (ID_ESTACION) REFERENCES ESTACIONES(ID_ESTACION),

    CONSTRAINT FK_DISPOSITIVOS_BUSES
        FOREIGN KEY (ID_BUS) REFERENCES BUSES(ID_BUS),
    CONSTRAINT UQ_DISPOSITIVOS_CODIGO UNIQUE (CODIGO_INVENTARIO),
    CONSTRAINT CK_DISPOSITIVOS_TIPO
        CHECK (TIPO IN (
            'TAT',
            'TCP',
            'CONTROL_ACCESO',
            'LECTOR',
            'OTRO'
        )),
    CONSTRAINT CK_DISPOSITIVOS_ESTADO
        CHECK (ESTADO IN (
            'ACTIVO',
            'INACTIVO',
            'MANTENIMIENTO',
            'DESCONECTADO'
        )),
    CONSTRAINT CK_DISPOSITIVOS_UBICACION
        CHECK (
            (ID_ESTACION IS NOT NULL AND ID_BUS IS NULL)
            OR
            (ID_ESTACION IS NULL AND ID_BUS IS NOT NULL)
        )
);

/* ============================================================
   14. MOVIMIENTOS DE PASAJEROS
   ============================================================ */

CREATE TABLE MOVIMIENTOS_PASAJEROS (
    ID_MOVIMIENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PASAJERO NUMBER,
    ID_TICKET NUMBER,
    ID_ESTACION NUMBER NOT NULL,
    ID_ACCESO NUMBER,
    TIPO_MOVIMIENTO VARCHAR2(20) NOT NULL,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESULTADO VARCHAR2(20) DEFAULT 'VALIDADO' NOT NULL,

    CONSTRAINT PK_MOVIMIENTOS PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_PASAJEROS
        FOREIGN KEY (ID_PASAJERO) REFERENCES PASAJEROS(ID_PASAJERO),
    CONSTRAINT FK_MOV_TICKETS
        FOREIGN KEY (ID_TICKET) REFERENCES TICKETS(ID_TICKET),
    CONSTRAINT FK_MOV_ESTACIONES
        FOREIGN KEY (ID_ESTACION) REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT FK_MOV_ACCESOS
        FOREIGN KEY (ID_ACCESO) REFERENCES ACCESOS(ID_ACCESO),
    CONSTRAINT CK_MOV_TIPO
        CHECK (TIPO_MOVIMIENTO IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT CK_MOV_RESULTADO

        CHECK (RESULTADO IN ('VALIDADO', 'RECHAZADO'))
);

/* ============================================================
   15. RECORRIDOS DE BUSES
   ============================================================ */

CREATE TABLE RECORRIDOS (
    ID_RECORRIDO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_BUS NUMBER NOT NULL,
    ID_LINEA NUMBER NOT NULL,
    ID_PILOTO NUMBER NOT NULL,
    FECHA_INICIO TIMESTAMP NOT NULL,
    FECHA_FIN TIMESTAMP,
    ESTADO VARCHAR2(30) DEFAULT 'PROGRAMADO' NOT NULL,

    CONSTRAINT PK_RECORRIDOS PRIMARY KEY (ID_RECORRIDO),
    CONSTRAINT FK_REC_BUSES
        FOREIGN KEY (ID_BUS) REFERENCES BUSES(ID_BUS),
    CONSTRAINT FK_REC_LINEAS
        FOREIGN KEY (ID_LINEA) REFERENCES LINEAS(ID_LINEA),
    CONSTRAINT FK_REC_PILOTOS
        FOREIGN KEY (ID_PILOTO) REFERENCES PILOTOS(ID_PILOTO),
    CONSTRAINT CK_REC_FECHAS
        CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO),
    CONSTRAINT CK_REC_ESTADO
        CHECK (ESTADO IN (
            'PROGRAMADO',
            'EN_CURSO',
            'FINALIZADO',
            'CANCELADO'
        ))
);

/* ============================================================
   16. CONTROL DE PASAJEROS EN BUSES
   ============================================================ */

CREATE TABLE CONTROL_PASAJEROS (
    ID_CONTROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_RECORRIDO NUMBER NOT NULL,
    ID_ESTACION NUMBER NOT NULL,
    PASAJEROS_ABORDAN NUMBER DEFAULT 0 NOT NULL,
    PASAJEROS_DESCIENDEN NUMBER DEFAULT 0 NOT NULL,
    OCUPACION_CALCULADA NUMBER DEFAULT 0 NOT NULL,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_CONTROL_PASAJEROS PRIMARY KEY (ID_CONTROL),
    CONSTRAINT FK_CP_RECORRIDOS
        FOREIGN KEY (ID_RECORRIDO)
        REFERENCES RECORRIDOS(ID_RECORRIDO),

    CONSTRAINT FK_CP_ESTACIONES
        FOREIGN KEY (ID_ESTACION)
        REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT CK_CP_ABORDAN
        CHECK (PASAJEROS_ABORDAN >= 0),
    CONSTRAINT CK_CP_DESCIENDEN
        CHECK (PASAJEROS_DESCIENDEN >= 0),
    CONSTRAINT CK_CP_OCUPACION
        CHECK (OCUPACION_CALCULADA >= 0)
);

/* ============================================================
   17. ALERTAS OPERATIVAS
   ============================================================ */

CREATE TABLE ALERTAS (
    ID_ALERTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_BUS NUMBER,
    ID_ESTACION NUMBER,
    ID_RECORRIDO NUMBER,
    TIPO_ALERTA VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(500) NOT NULL,
    NIVEL VARCHAR2(20) DEFAULT 'MEDIA' NOT NULL,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,

    CONSTRAINT PK_ALERTAS PRIMARY KEY (ID_ALERTA),
    CONSTRAINT FK_ALERTAS_BUSES
        FOREIGN KEY (ID_BUS) REFERENCES BUSES(ID_BUS),
    CONSTRAINT FK_ALERTAS_ESTACIONES
        FOREIGN KEY (ID_ESTACION) REFERENCES ESTACIONES(ID_ESTACION),
    CONSTRAINT FK_ALERTAS_RECORRIDOS
        FOREIGN KEY (ID_RECORRIDO)
        REFERENCES RECORRIDOS(ID_RECORRIDO),
    CONSTRAINT CK_ALERTAS_NIVEL
        CHECK (NIVEL IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT CK_ALERTAS_ESTADO
        CHECK (ESTADO IN ('PENDIENTE', 'ATENDIDA', 'CANCELADA'))
);

/* ============================================================
   18. INCIDENTES
